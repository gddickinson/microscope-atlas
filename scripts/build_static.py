"""Export the static site to site/ (default) for GitHub Pages or any static host.

Every API response is generated by calling the real FastAPI app through its TestClient, so the static site shows
exactly what the server would. Endpoints with query parameters (system and fluorophore search) are answered in
the browser by static_api.js from the full lists. Tools that need Python on the server (flagged python: true)
show a notice instead.

Run: .venv/bin/python scripts/build_static.py [--out site]
"""
import argparse
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from fastapi.testclient import TestClient  # noqa: E402

from atlas import catalog, content  # noqa: E402
from atlas.web.app import app  # noqa: E402

CONTENT_NAMES = ["history", "glossary", "fundamentals", "simulations", "portfolio", "community", "videos", "cells", "nobel"]


def endpoints() -> list[str]:
    paths = ["/stats", "/techniques", "/techniques/matrix", "/systems", "/systems/facets", "/manufacturers", "/components/detectors",
             "/components/objectives", "/components/light_sources", "/components/filters", "/spectra", "/papers", "/images"]
    paths += [f"/techniques/{t['id']}" for t in catalog.techniques()]
    paths += [f"/systems/{s['id']}" for s in catalog.systems()]
    paths += [f"/content/{n}" for n in CONTENT_NAMES]
    return paths


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "site"))
    out = Path(ap.parse_args().out)
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(ROOT / "atlas" / "web" / "static", out / "static", ignore=shutil.ignore_patterns("package.json", "*.test.mjs"))
    client = TestClient(app)
    n = 0
    for path in endpoints():
        r = client.get("/api" + path)
        r.raise_for_status()
        dest = out / "api" / (path.lstrip("/") + ".json")
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(json.dumps(r.json(), ensure_ascii=False, separators=(",", ":")))
        n += 1
    imgs = client.get("/api/portfolio/images", params={"public": True}).json()
    (out / "api" / "portfolio").mkdir(parents=True, exist_ok=True)
    (out / "api" / "portfolio" / "images.json").write_text(json.dumps(imgs))
    full = client.get("/api/fluorophores", params={"limit": 100000}).json()
    (out / "api" / "fluorophores.json").write_text(json.dumps(full, separators=(",", ":")))
    # portfolio images, if any were approved and published under data/portfolio
    if (ROOT / "data" / "images").exists():
        shutil.copytree(ROOT / "data" / "images", out / "images")
    pimg = ROOT / "data" / "portfolio"
    if pimg.exists():
        shutil.copytree(pimg, out / "portfolio")
    index = (ROOT / "atlas" / "web" / "static" / "index.html").read_text()
    index = index.replace("<head>", "<head>\n<script>window.ATLAS_STATIC = true;</script>", 1)
    (out / "index.html").write_text(index)
    (out / ".nojekyll").write_text("")
    size = sum(f.stat().st_size for f in out.rglob("*") if f.is_file()) / 1e6
    print(f"static site: {n + 1} API files, {size:.1f} MB in {out}")
    assert len(content.technique_pages()) == len(catalog.techniques())


if __name__ == "__main__":
    main()
